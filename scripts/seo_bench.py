#!/usr/bin/env python3
"""Run the same prompt across ManifoldGen video models and record real outputs.

Results land in scripts/seo_bench_results.json and frontend/lib/seo/bench-results.ts
(the data module behind /leaderboard, /compare/*, /best/*). Idempotent: completed
entries are skipped, so re-running picks up new models or retries failures.

Usage:
  python3 scripts/seo_bench.py                 # full matrix
  python3 scripts/seo_bench.py --only wan      # one model key
  python3 scripts/seo_bench.py --status        # show progress
"""

